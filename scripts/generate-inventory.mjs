#!/usr/bin/env node
/**
 * Component inventory generator.
 * Scans shared/ui and features/<feature>/ui for React components and emits
 * COMPONENT_INVENTORY.md so reviewers (and Claude Code) can match new markup
 * against existing primitives instead of inventing duplicates.
 *
 * Run: pnpm design:inventory
 */

import { Project, SyntaxKind } from 'ts-morph'
import { mkdirSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(fileURLToPath(import.meta.url), '../..')
const OUTPUT = resolve(ROOT, 'COMPONENT_INVENTORY.md')

const project = new Project({
  tsConfigFilePath: resolve(ROOT, 'tsconfig.json'),
  skipAddingFilesFromTsConfig: true,
})

const globs = ['shared/ui/**/*.tsx', 'features/*/ui/**/*.tsx']
project.addSourceFilesAtPaths(globs.map((g) => resolve(ROOT, g)))

const sources = project.getSourceFiles()

const buckets = new Map() // section title -> entries[]
function bucketFor(filePath) {
  const rel = relative(ROOT, filePath).replaceAll('\\', '/')
  if (rel.startsWith('shared/ui/')) return 'shared/ui (shadcn primitives — DO NOT MODIFY)'
  const featureMatch = rel.match(/^features\/([^/]+)\/ui\//)
  if (featureMatch) return `features/${featureMatch[1]}/ui`
  return 'other'
}

function extractCvaVariants(sourceFile) {
  // Find: const X = cva(base, { variants: { ... }, defaultVariants: { ... } })
  const result = {}
  for (const decl of sourceFile.getVariableDeclarations()) {
    const init = decl.getInitializer()
    if (!init) continue
    if (init.getKind() !== SyntaxKind.CallExpression) continue
    const expr = init.getExpression?.()
    if (!expr || expr.getText() !== 'cva') continue
    const args = init.getArguments()
    if (args.length < 2) continue
    const config = args[1]
    if (config.getKind() !== SyntaxKind.ObjectLiteralExpression) continue
    const variantsProp = config.getProperty('variants')
    if (!variantsProp) continue
    const variantsObj = variantsProp.getInitializer?.()
    if (!variantsObj || variantsObj.getKind() !== SyntaxKind.ObjectLiteralExpression) continue
    const variants = {}
    for (const v of variantsObj.getProperties()) {
      const name = v.getName?.()
      const valueObj = v.getInitializer?.()
      if (!name || !valueObj || valueObj.getKind() !== SyntaxKind.ObjectLiteralExpression) continue
      variants[name] = valueObj
        .getProperties()
        .map((p) => p.getName?.())
        .filter(Boolean)
    }
    const defaultsProp = config.getProperty('defaultVariants')
    let defaults = {}
    if (defaultsProp) {
      const defaultsObj = defaultsProp.getInitializer?.()
      if (defaultsObj && defaultsObj.getKind() === SyntaxKind.ObjectLiteralExpression) {
        for (const p of defaultsObj.getProperties()) {
          const k = p.getName?.()
          const initText = p.getInitializer?.()?.getText?.()
          if (k && initText) defaults[k] = initText.replace(/['"]/g, '')
        }
      }
    }
    result[decl.getName()] = { variants, defaults }
  }
  return result
}

function extractPropsForComponent(sourceFile, componentName) {
  // Heuristic: function ComponentName({...}: PropsType) { ... }
  const fn = sourceFile.getFunction(componentName)
  if (!fn) return null
  const params = fn.getParameters()
  if (params.length === 0) return null
  const typeNode = params[0].getTypeNode()
  return typeNode ? typeNode.getText() : null
}

function summarize(sourceFile) {
  const exports = new Set()
  for (const [name] of sourceFile.getExportedDeclarations()) {
    exports.add(name)
  }
  const cva = extractCvaVariants(sourceFile)
  const components = []
  for (const name of exports) {
    if (/^[A-Z]/.test(name)) {
      const propsType = extractPropsForComponent(sourceFile, name)
      components.push({ name, propsType })
    }
  }
  return {
    components,
    otherExports: [...exports].filter((n) => !/^[A-Z]/.test(n)),
    cva,
  }
}

for (const sf of sources) {
  const filePath = sf.getFilePath()
  const rel = relative(ROOT, filePath).replaceAll('\\', '/')
  const bucket = bucketFor(filePath)
  const summary = summarize(sf)
  if (summary.components.length === 0 && summary.otherExports.length === 0) continue
  if (!buckets.has(bucket)) buckets.set(bucket, [])
  buckets.get(bucket).push({ rel, ...summary })
}

const featureBuckets = [...buckets.keys()].filter((k) => k.startsWith('features/'))
if (featureBuckets.length === 0) {
  buckets.set('features/* (none yet — will populate as features are added)', [])
}

const lines = []
lines.push('<!-- AUTO-GENERATED by scripts/generate-inventory.mjs — do not edit by hand -->')
lines.push('# Component Inventory')
lines.push('')
lines.push('Reviewers and Claude Code consult this file before introducing new components.')
lines.push('Reuse existing primitives whenever possible.')
lines.push('')

const sortedBuckets = [...buckets.keys()].sort((a, b) => {
  if (a.startsWith('shared/')) return -1
  if (b.startsWith('shared/')) return 1
  return a.localeCompare(b)
})

for (const bucket of sortedBuckets) {
  lines.push(`## ${bucket}`)
  lines.push('')
  const entries = buckets.get(bucket) ?? []
  if (entries.length === 0) {
    lines.push('_No components yet._')
    lines.push('')
    continue
  }
  for (const entry of entries.sort((a, b) => a.rel.localeCompare(b.rel))) {
    lines.push(`### \`${entry.rel}\``)
    if (entry.components.length > 0) {
      lines.push('')
      lines.push('| Component | Props type |')
      lines.push('| --- | --- |')
      for (const c of entry.components) {
        const props = (c.propsType ?? '—').replace(/\|/g, '\\|').replace(/\n/g, ' ')
        lines.push(`| \`${c.name}\` | \`${props}\` |`)
      }
    }
    if (entry.otherExports.length > 0) {
      lines.push('')
      lines.push(`Other exports: ${entry.otherExports.map((n) => `\`${n}\``).join(', ')}`)
    }
    const cvaEntries = Object.entries(entry.cva)
    if (cvaEntries.length > 0) {
      lines.push('')
      for (const [name, { variants, defaults }] of cvaEntries) {
        lines.push(`**\`${name}\` variants:**`)
        for (const [vk, options] of Object.entries(variants)) {
          const def = defaults[vk] ? ` (default: \`${defaults[vk]}\`)` : ''
          lines.push(`- \`${vk}\`: ${options.map((o) => `\`${o}\``).join(', ')}${def}`)
        }
      }
    }
    lines.push('')
  }
}

if (!existsSync(dirname(OUTPUT))) mkdirSync(dirname(OUTPUT), { recursive: true })
writeFileSync(OUTPUT, lines.join('\n'), 'utf8')

console.log(`Wrote ${relative(ROOT, OUTPUT)} (${sources.length} source files scanned)`)
